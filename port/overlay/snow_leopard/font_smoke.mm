static int CountInk(const SkBitmap& bitmap, int top, int bottom) {
  int count = 0;
  for (int y = top; y < bottom; ++y)
    for (int x = 10; x < bitmap.width() - 10; ++x)
      if (bitmap.getColor(x, y) != SK_ColorWHITE)
        ++count;
  return count;
}

int main(int argc, char** argv) {
  NSAutoreleasePool* pool = [[NSAutoreleasePool alloc] init];
  const CGFloat rgba[] = {0.25, 0.5, 0.75, 0.625};
  NSColor* custom = [NSColor colorWithColorSpace:[NSColorSpace deviceRGBColorSpace]
                                    components:rgba count:4];
  if (skia::NSDeviceColorToSkColor(custom) != SkColorSetARGB(159, 64, 128, 191)) {
    fprintf(stderr, "FAIL custom device RGB color conversion\n");
    return 5;
  }
  SkColor background = skia::NSSystemColorToSkColor(NSColor.windowBackgroundColor);
  if (SkColorGetA(background) != 255) {
    fprintf(stderr, "FAIL native system pattern color conversion\n");
    return 6;
  }
  printf("PASS Skia custom RGB and native system pattern color conversion\n");

  sk_sp<SkFontMgr> manager = SkFontMgr_New_CoreText(nullptr);
  if (!manager || manager->countFamilies() <= 0) {
    fprintf(stderr, "FAIL CoreText font manager initialization\n");
    return 7;
  }
  SkBitmap bitmap;
  if (!bitmap.tryAllocN32Pixels(880, 400))
    return 8;
  SkCanvas canvas(bitmap);
  canvas.clear(SK_ColorWHITE);
  SkPaint paint;
  paint.setColor(SK_ColorBLACK);
  paint.setAntiAlias(true);
  const char* families[] = {"Helvetica", "Times", "Courier"};
  const char* text = "Snow Leopard / Chromium 124: Aa 0123456789";
  for (int i = 0; i < 3; ++i) {
    sk_sp<SkTypeface> typeface = manager->matchFamilyStyle(families[i], SkFontStyle());
    if (!typeface) {
      fprintf(stderr, "FAIL %s typeface lookup\n", families[i]);
      return 9;
    }
    SkFont font(typeface, 27);
    font.setEdging(SkFont::Edging::kSubpixelAntiAlias);
    font.setSubpixel(true);
    if (font.measureText(text, strlen(text), SkTextEncoding::kUTF8) < 100)
      return 10;
    canvas.drawSimpleText(text, strlen(text), SkTextEncoding::kUTF8,
                          20, 55 + i * 80, font, paint);
    int ink = CountInk(bitmap, 10 + i * 80, 70 + i * 80);
    printf("%s %s Skia glyph rasterization: %d nonwhite pixels\n",
           ink > 500 ? "PASS" : "FAIL", families[i], ink);
    if (ink <= 500)
      return 11;
  }

  // Unlike a system font lookup, this exercises the missing Lion data->font
  // entry point and the font-data lifetime through Skia's own manager.
  sk_sp<SkTypeface> embedded = manager->makeFromData(
      SkData::MakeWithCopy(kSpiderSymbol_ttf, sizeof(kSpiderSymbol_ttf)), 0);
  if (!embedded || embedded->countGlyphs() <= 3) {
    fprintf(stderr, "FAIL Skia embedded TrueType font construction\n");
    return 12;
  }
  SkFont embedded_font(embedded, 60);
  embedded_font.setEdging(SkFont::Edging::kAntiAlias);
  embedded_font.setSubpixel(true);
  const SkGlyphID spider = 3;
  paint.setColor(SkColorSetRGB(35, 90, 170));
  canvas.drawSimpleText(&spider, sizeof(spider), SkTextEncoding::kGlyphID,
                        30, 335, embedded_font, paint);
  canvas.save();
  canvas.translate(180, 335);
  canvas.rotate(-20);
  canvas.drawSimpleText(&spider, sizeof(spider), SkTextEncoding::kGlyphID,
                        0, 0, embedded_font, paint);
  canvas.restore();
  int embedded_ink = CountInk(bitmap, 260, 390);
  printf("%s Skia embedded TrueType and rotated glyphs: %d nonwhite pixels\n",
         embedded_ink > 300 ? "PASS" : "FAIL", embedded_ink);
  if (embedded_ink <= 300)
    return 13;

  SkPixmap pixels;
  if (!bitmap.peekPixels(&pixels))
    return 14;
  SkDynamicMemoryWStream encoded;
  if (!SkPngEncoder::Encode(&encoded, pixels, SkPngEncoder::Options()))
    return 15;
  sk_sp<SkData> png = encoded.detachAsData();
  const char* path = argc > 1 ? argv[1] : "font-smoke-124.png";
  FILE* output = fopen(path, "wb");
  if (!output)
    return 16;
  bool written = fwrite(png->data(), 1, png->size(), output) == png->size();
  bool closed = fclose(output) == 0;
  [pool drain];
  if (!written || !closed)
    return 17;
  printf("PASS PNG saved to %s\n", path);
  return 0;
}
